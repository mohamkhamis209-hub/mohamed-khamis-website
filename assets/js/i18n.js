/**
 * i18n Controller
 */
class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('mk_lang') || 'ar';
    this.subscribers = [];
  }

  init() {
    this.applyLanguage(this.currentLang);
  }

  getLang() {
    return this.currentLang;
  }

  isRTL() {
    return this.currentLang === 'ar';
  }

  t(key) {
    const langDict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.ar;
    return langDict[key] || TRANSLATIONS.ar[key] || key;
  }

  setLanguage(lang) {
    if (lang !== 'ar' && lang !== 'en') return;
    this.currentLang = lang;
    localStorage.setItem('mk_lang', lang);
    this.applyLanguage(lang);
    this.notifySubscribers();
  }

  toggleLanguage() {
    this.setLanguage(this.currentLang === 'ar' ? 'en' : 'ar');
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.body.classList.toggle('lang-ar', lang === 'ar');
    document.body.classList.toggle('lang-en', lang === 'en');

    // Translate all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.getAttribute('placeholder')) {
            el.setAttribute('placeholder', translation);
          }
        } else {
          el.textContent = translation;
        }
      }
    });

    // Translate placeholder attributes specifically
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) el.setAttribute('placeholder', translation);
    });

    // Translate title or aria-label attributes
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translation = this.t(key);
      if (translation) el.setAttribute('title', translation);
    });
  }

  onLanguageChange(callback) {
    this.subscribers.push(callback);
  }

  notifySubscribers() {
    this.subscribers.forEach(cb => {
      try { cb(this.currentLang); } catch (e) { console.error('i18n callback error:', e); }
    });
  }
}

export const i18n = new I18nManager();
